func ellipsePoint(rx, ry, phi, cx, cy, theta float64) (float64, float64) {
	sinTheta, cosTheta := math.Sincos(theta)
	sinPhi, cosPhi := math.Sincos(phi)
	x := cx + rx*cosTheta*cosPhi - ry*sinTheta*sinPhi
	y := cy + rx*cosTheta*sinPhi + ry*sinTheta*cosPhi
	return x, y
}
func nearlyEqual(a, b float64) bool { return math.Abs(a-b) <= epsilon }
func ellipseDerivative(rx, ry, phi float64, sweep bool, theta float64) (float64, float64) {
	sinTheta, cosTheta := math.Sincos(theta)
	sinPhi, cosPhi := math.Sincos(phi)
	dx := -rx*sinTheta*cosPhi - ry*cosTheta*sinPhi
	dy := -rx*sinTheta*sinPhi + ry*cosTheta*cosPhi
	if !sweep {
		return -dx, -dy
	}
	return dx, dy
}

