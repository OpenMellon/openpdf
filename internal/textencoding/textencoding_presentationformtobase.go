func NewTrueTypeFontEncoder(runeToGIDMap map[rune]GID) *TrueTypeFontEncoder {
	gidMap := syncmap.MakeRuneUint16Map(len(runeToGIDMap))
	for r, gid := range runeToGIDMap {
		gidMap.Write(r, uint16(gid))
	}
	return &TrueTypeFontEncoder{runeToGID: gidMap, usedRunes: syncmap.MakeRuneSet(0)}
}

