func (enc *IdentityEncoder) ToPdfObject() core.PdfObject {
	if enc.name != "" {
		return core.MakeName(enc.name)
	}
	return core.MakeNull()
}

func (m *charCodeGlyphNameMap) Length() int {
	m.mu.RLock()
	defer m.mu.RUnlock()
	return len(m.data)
}

func (enc *IdentityEncoder) CharcodeToGID(code CharCode) (GID, bool) {
	enc.usedGIDs.Write(uint16(code))
	if enc.cidToGID != nil {
		if int(code) < len(enc.cidToGID) {
			return GID(enc.cidToGID[code]), true
		}
		return 0, false
	}
	return GID(code), true
}

func NewCustomSimpleTextEncoder(encoding, differences map[CharCode]GlyphName) (SimpleEncoder, error) {
	if len(encoding) == 0 {
		return nil, errors.New("empty custom encoding")
	}
	const customEncodingName = "custom"
	byteToRune := syncmap.MakeByteRuneMap(len(encoding))
	for code, glyph := range encoding {
		r, ok := GlyphToRune(glyph)
		if !ok {
			common.Log.Debug("ERROR: Unknown glyph. %q", glyph)
			continue
		}
		byteToRune.Write(byte(code), r)
	}
	enc := newSimpleEncoding(customEncodingName, byteToRune)
	if len(differences) != 0 {
		enc = ApplyDifferences(enc, differences)
	}
	return enc, nil
}

func (enc *differencesEncoding) RuneToCharcode(r rune) (CharCode, bool) {
	if b, ok := enc.runeToByte.Read(r); ok {
		return CharCode(b), true
	}
	return enc.base.RuneToCharcode(r)
}

func (enc CMapEncoder) charcodeToString(code CharCode) (string, bool) {
	if enc.cidToUnicode == nil {
		return MissingCodeString, false
	}
	cid := cmap.CharCode(code)
	if enc.codeToCID != nil {
		var ok bool
		if cid, ok = enc.codeToCID.CharcodeToCID(cmap.CharCode(code)); !ok {
			return MissingCodeString, false
		}
	}
	return enc.cidToUnicode.CharcodeToUnicode(cid)
}

func (m *simpleMapping) init() {
	m.runeToByte = syncmap.MakeRuneByteMap(m.byteToRune.Length())
	m.byteToRune.Range(func(b byte, r rune) (stop bool) {
		if prev, found := m.runeToByte.Read(r); !found || b < prev {
			m.runeToByte.Write(r, b)
		}
		return false
	})
}

